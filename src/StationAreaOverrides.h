inline std::string_view AreaAt(const std::string_view id,
                              const double latitude, const double longitude) {
    // Require the same station and location; four-character IDs can be reused worldwide.
    for (const auto& row : kEvidence) {
        if (row.id == id && std::abs(row.latitude - latitude) < 0.005
            && std::abs(row.longitude - longitude) < 0.005) return row.area;
    }
    return {};
}
