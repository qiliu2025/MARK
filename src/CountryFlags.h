inline int Index(std::string_view alpha3) {
    // Retain this atlas entry for geographic display.
    if (CountryPolicy::NeutralArea(alpha3) && alpha3 != "ATA") return -1;
    for (std::size_t index = 0; index < sizeof(kFlagCodes) / sizeof(kFlagCodes[0]); ++index) {
        if (alpha3 == kFlagCodes[index].alpha3) return static_cast<int>(index);
    }
    return -1;
}
inline bool IsKnownArea(std::string_view area) {
    if (CountryPolicy::Find(area)) return true;
    return Index(area) >= 0;
}
inline std::string ResolveArea(std::string_view providerCountry,
                               std::string_view siteLogCountry,
                               std::string_view stationId,
                               bool legacyNgsFips = false) {
    const auto logArea = NormalizeArea(siteLogCountry);
    auto providerArea = NormalizeArea(providerCountry);
    if (legacyNgsFips && providerArea == "BFA") {
        // NGS's historical FIPS BF means Bahamas; ISO BF means Burkina Faso.
        // This override is provider-specific and never applies to a Site Log
        // or to user-entered ISO country scope codes.
        std::string token(providerCountry);
        token.erase(0, token.find_first_not_of(" \t\r\n"));
        const auto end = token.find_last_not_of(" \t\r\n");
        if (end != std::string::npos) token.resize(end + 1);
        if (token == "BF" || token == "bf" || token == "Bf" || token == "bF") providerArea = "BHS";
    }
    const auto idArea = stationId.size() == 9
        ? NormalizeArea(stationId.substr(6, 3)) : std::string();
    if (IsKnownArea(logArea)) {
        // Preserve source-area detail when its normalized code is unchanged.
        if (!CountryPolicy::Find(logArea)) {
            for (const auto& area : {providerArea, idArea}) {
                const auto* rule = CountryPolicy::Find(area);
                if (rule && rule->country == logArea) return area;
            }
        }
        return logArea;
    }
    if (IsKnownArea(providerArea)) return providerArea;
    if (stationId.size() == 9) {
        if (IsKnownArea(idArea)) return idArea;
    }
    return providerArea.size() == 3 ? providerArea : std::string("UNK");
}
inline std::string ResolveStationArea(std::string_view providerCountry,
                                      std::string_view siteLogCountry,
                                      std::string_view stationId,
                                      bool legacyNgsFips,
                                      double latitude, double longitude) {
    const auto region = CountryGeoPolicy::AreaAt(longitude, latitude);
    if (!region.empty()) {
        if (region == "CHN") {
            const auto original = ResolveArea(providerCountry, siteLogCountry, stationId, legacyNgsFips);
            if (Normalize(original) == "CHN") return original;
        }
        return std::string(region);
    }
    return ResolveArea(providerCountry, siteLogCountry, stationId, legacyNgsFips);
}
inline std::wstring Emoji(std::string_view alpha3) {
    std::string alpha2;
    for (const auto& code : kFlagCodes) if (alpha3 == code.alpha3) { alpha2 = std::string(code.alpha2); break; }
    if (alpha2.size() != 2) return {};
    std::wstring result;
    for (char c : alpha2) {
        const unsigned int codePoint = 0x1F1E6U
            + static_cast<unsigned int>(c - 'A');
        const unsigned int value = codePoint - 0x10000U;
        result.push_back(static_cast<wchar_t>(0xD800U + (value >> 10U)));
        result.push_back(static_cast<wchar_t>(0xDC00U + (value & 0x3FFU)));
    }
    return result;
}
