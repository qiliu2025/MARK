inline std::string NormalizeArea(std::string_view value) {
    std::string upper(value);
    for (char& c : upper) if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    const auto whitespace = [](const char c) {
        return c == ' ' || c == '\t' || c == '\r' || c == '\n';
    };
    while (!upper.empty() && whitespace(upper.front())) upper.erase(upper.begin());
    while (!upper.empty() && whitespace(upper.back())) upper.pop_back();
    for (const auto& alias : CountryPolicy::kAliases) {
        if (upper == alias.value) return std::string(alias.area);
    }
    for (const auto& alias : CountryPolicy::kIsoAliases) {
        if (upper == alias.value) return std::string(alias.area);
    }
    for (const auto& alias : kAliases) {
        if (upper != alias.value) continue;
        return std::string(alias.alpha3);
    }
    if (upper == "ROC") return "TWN";
    return upper;
}
inline std::string Normalize(std::string_view value) {
    return CountryPolicy::CountryCode(NormalizeArea(value));
}
