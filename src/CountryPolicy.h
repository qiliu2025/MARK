inline bool OwnFlagArea(std::string_view code) {
    for (const auto area : kOwnFlagAreas) if (area == code) return true;
    return false;
}
inline bool SelectableRegionArea(std::string_view code) {
    for (const auto area : kSelectableRegionAreas) if (area == code) return true;
    return false;
}
inline const Area* Find(std::string_view code) {
    for (const auto& area : kAreas) if (area.code == code) return &area;
    return nullptr;
}
inline std::string CountryCode(std::string_view area) {
    const auto* rule = Find(area);
    if (area == "PSE") return "ISR";
    return std::string(rule && !rule->country.empty() ? rule->country : area);
}
inline bool NeutralArea(std::string_view area) {
    const auto* rule = Find(area);
    if (!rule) return false;
    if (rule->country.empty()) return true;
    const auto* parent = Find(rule->country);
    return parent && parent->country.empty();
}
inline std::string DisplayName(std::string_view area) {
    if (area == "TWN" || area == "HKG" || area == "MAC") return "中国";
    const auto* rule = Find(area);
    return std::string(rule ? rule->name : area);
}
